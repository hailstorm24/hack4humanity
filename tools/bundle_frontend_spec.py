"""Regenerate frontend-openapi.yaml from bot-management-api.yaml + common.yaml.

    python3 tools/bundle_frontend_spec.py          # write the bundle
    python3 tools/bundle_frontend_spec.py --check  # exit 1 if the bundle is stale

Needs PyYAML. The bundle inlines common.yaml's schemas so frontend tools that
can't follow cross-file $refs can read it.
"""
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "frontend-openapi.yaml")
SERVERS = [
    {"url": "https://h4h-narrative-stubs.onrender.com/v1",
     "description": "Hosted stub (Render free tier; sleeps when idle)"},
    {"url": "http://127.0.0.1:8000/v1", "description": "Local stub (stubs/run.sh)"},
]


def build():
    with open(os.path.join(ROOT, "bot-management-api.yaml"), encoding="utf-8") as f:
        spec = yaml.safe_load(f)
    with open(os.path.join(ROOT, "common.yaml"), encoding="utf-8") as f:
        common = yaml.safe_load(f)

    spec["servers"] = SERVERS
    spec["info"]["title"] = "Bot Management API (frontend bundle)"
    spec["info"]["description"] = (spec["info"]["description"].rstrip()
                                   + "\n\nGenerated from bot-management-api.yaml + common.yaml"
                                   " by tools/bundle_frontend_spec.py; edit those, not this file.\n")
    comps = spec.setdefault("components", {})
    comps.setdefault("schemas", {}).update(common["components"]["schemas"])
    comps.setdefault("responses", {}).update(common["components"]["responses"])

    def localize(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if k == "$ref" and isinstance(v, str) and v.startswith("common.yaml#"):
                    o[k] = v[len("common.yaml"):]
                else:
                    localize(v)
        elif isinstance(o, list):
            for x in o:
                localize(x)

    localize(spec)
    text = ("# GENERATED by tools/bundle_frontend_spec.py from bot-management-api.yaml + common.yaml.\n"
            + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=100))

    # Every $ref must resolve inside the bundle.
    doc = yaml.safe_load(text)
    broken = []

    def check(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if k == "$ref":
                    node = doc
                    try:
                        for part in v.lstrip("#/").split("/"):
                            node = node[part]
                    except (KeyError, TypeError):
                        broken.append(v)
                else:
                    check(v)
        elif isinstance(o, list):
            for x in o:
                check(x)

    check(doc)
    if broken:
        sys.exit(f"unresolved $refs in bundle: {broken}")
    return text


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            sys.exit("frontend-openapi.yaml is stale; run: python3 tools/bundle_frontend_spec.py")
        print("frontend-openapi.yaml is up to date")
    else:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(OUT, ROOT)}")
